export function guessSubtopic(category: Category, text: string): string {
  const subs = SUBTOPICS[category];
  let best = subs[0], bestScore = 0;
  for (const s of subs) {
    const score = (SUBTOPIC_KEYWORDS[s] ?? []).reduce((n, k) => n + (text.includes(k) ? 1 : 0), 0);
    if (score > bestScore) { best = s; bestScore = score; }
  }
  return best;
}

const STRONG = ['너무', '진짜', '정말', '매번', '최악', '위험', '도저히', '항상', '심각', '화가', '짜증', '못 ', '안 돼', '!!'];

/** 불만 강도 1~3 (키워드 수 기준) */
export function sentimentOf(text: string): 1 | 2 | 3 {
  const n = STRONG.reduce((s, k) => s + (text.includes(k) ? 1 : 0), 0);
  return n >= 2 ? 3 : n === 1 ? 2 : 1;
}
